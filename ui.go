// drawAIPlayerAreas draws the 4 AI player areas with face art
func (sl *ScreenLayout) drawAIPlayerAreas() {
	// AI player names and their positions - must match main.go names
	aiPlayers := []struct {
		name   string
		x, y   int
		isLeft bool
	}{
		{"PHOOJA", sl.AIPlayer1X, sl.AIPlayer1Y, true},     // Top-left
		{"ASH-TAAC", sl.AIPlayer2X, sl.AIPlayer2Y, false}, // Top-right
		{"OOLANGA", sl.AIPlayer3X, sl.AIPlayer3Y, true},    // Bottom-left
		{"KY'ALA", sl.AIPlayer4X, sl.AIPlayer4Y, false},     // Bottom-right
	}

	for i, player := range aiPlayers {
		// Draw portrait from ANSI file
		sl.drawSimpleFaceArt(player.x, player.y, i)

		// Draw player name and credits  
		if player.isLeft {
			MoveCursor(player.x+portraitWidth+1, player.y)
		} else {
			// Right side players: use same fixed 16-column positioning as UpdatePlayerInfo
			MoveCursor(player.x-16, player.y)
		}
		fmt.Printf("%s%s%s", CyanHi, player.name, Reset)
	}
}

// drawHumanPlayerArea draws the human player area at bottom center
func (sl *ScreenLayout) drawHumanPlayerArea() {
	// Draw player name area
	MoveCursor(sl.HumanPlayerX, sl.HumanNameY)
	fmt.Printf("%s[Player Area]%s", GreenHi, Reset)
}

// drawSimpleFaceArt draws character faces using external portraits
func (sl *ScreenLayout) drawSimpleFaceArt(x, y, playerIndex int) {
	// Use external portrait from ANSI file
	if sl.PortraitManager != nil {
		sl.PortraitManager.RenderPortrait(x, y, playerIndex)
	}
}

// drawGameLogBorder fills the entire game log area with blue background (no borders)
func (sl *ScreenLayout) drawGameLogBorder() {
	// Use exact positioning from reference file
	logX := sl.GameLogX
	logY := sl.GameLogY
	logW := sl.GameLogW

	// Fill entire game log area with blue background
	for i := 0; i <= sl.GameLogH; i++ {
		MoveCursor(logX, logY+i)
		fmt.Printf("\x1b[30;44m%s\x1b[0m", strings.Repeat(" ", logW))
	}
}

// UpdateHeader updates the turn indicator and game status
func (sl *ScreenLayout) UpdateHeader(round, handPot, sabaccPot, deckSize int, currentPlayer string) {
	// Update turn indicator
	sl.drawTurnIndicator(currentPlayer)

	// Update pot info
	sl.drawPotInfo(handPot, sabaccPot, 0)

	// Update bottom status line with pot information
	sl.UpdateStatusLine(round, handPot, sabaccPot, deckSize)
}

func (sl *ScreenLayout) drawTurnIndicator(currentPlayer string) {
	// Position turn indicator in a safe area - above the human player name
	MoveCursor(25, 14)
	fmt.Print(strings.Repeat(" ", 40)) // Clear wider area
	MoveCursor(25, 14)
	if currentPlayer == "Human" || currentPlayer == "" {
		fmt.Printf("%s\x10 YOUR TURN \x11%s", YellowHi, Reset)
	} else {
		// Extract just the player name (before any space or status text)
		playerName := strings.Fields(currentPlayer)[0]
		fmt.Printf("%s\x10 %s'S TURN \x11%s", YellowHi, strings.ToUpper(playerName), Reset)
	}
}

func (sl *ScreenLayout) drawPotInfo(gamePot, sabaccPot, sidePot int) {
	// Use struct's defined pot position coordinates
	
	// Clear the area first
	for i := 0; i < 3; i++ {
		MoveCursor(sl.PotInfoX, sl.PotInfoY+i)
		fmt.Print(strings.Repeat(" ", 25)) // Clear wider area
	}
	
	// Display pot information (right-aligned formatting)
	MoveCursor(sl.PotInfoX, sl.PotInfoY)
	fmt.Printf("  Game Pot: %d", gamePot)
	MoveCursor(sl.PotInfoX, sl.PotInfoY+1)
	fmt.Printf("Sabacc Pot: %d", sabaccPot)
	MoveCursor(sl.PotInfoX, sl.PotInfoY+2)
	fmt.Printf("  Side Pot: %d", sidePot)
}

// UpdateStatusLine updates the bottom status line with game info (CP437 style)
func (sl *ScreenLayout) UpdateStatusLine(round, handPot, sabaccPot, deckSize int) {
	MoveCursor(1, sl.StatusY)
	fmt.Print(EraseLine)

	// Create status line with cyan background like in reference file (without pot info since it's displayed separately)
	statusLeft := fmt.Sprintf("\x1b[36;46m     \x1b[0;30;46m \x1b[1;37mRound: \x1b[33m%d\x1b[36m \x1b[37m  Deck: \x1b[33m%d\x1b[37m \x1b[0;30;46m        \x1b[36;40m", round, deckSize)

	fmt.Print(statusLeft)

	// Fill rest of line to terminal width
	statusLen := len(stripANSI(statusLeft))
	if statusLen < sl.TerminalW {
		remaining := sl.TerminalW - statusLen
		fmt.Printf("\x1b[36;40m%s\x1b[37m", strings.Repeat(" ", remaining))
	}

	fmt.Print(Reset)
}

// UpdatePlayerInfo updates a player's name, credits, and total for new layout
func (sl *ScreenLayout) UpdatePlayerInfo(playerIndex int, name string, credits, total int, showTotal bool) {
	switch playerIndex {
	case 0: // Human player (bottom center)
		MoveCursor(sl.HumanPlayerX, sl.HumanNameY)
		fmt.Print(EraseLine)
		if showTotal {
			fmt.Printf("%s%s%s - Total: %s Credits: %d",
				GreenHi, name, Reset, displayHandValue(total), credits)
		} else {
			fmt.Printf("%s%s%s - Credits: %d", GreenHi, name, Reset, credits)
		}
	case 1, 2, 3, 4: // AI players (corners) - update name and credits on same line
		var x, y int
		var isLeft bool
		switch playerIndex {
		case 1: // Top-left (PHOOJA)
			x, y = sl.AIPlayer1X+portraitWidth+1, sl.AIPlayer1Y
			isLeft = true
		case 2: // Top-right (ASH-TAAC)  
			x, y = sl.AIPlayer2X, sl.AIPlayer2Y
			isLeft = false
		case 3: // Bottom-left (OOLANGA)
			x, y = sl.AIPlayer3X+portraitWidth+1, sl.AIPlayer3Y
			isLeft = true
		case 4: // Bottom-right (KY'ALA)
			x, y = sl.AIPlayer4X, sl.AIPlayer4Y
			isLeft = false
		}
		
		if isLeft {
			// Left side players: name followed by credits
			// Calculate exact space needed: name + space + $ + digits
			creditsText := fmt.Sprintf("$%d", credits)
			totalLength := len(name) + 1 + len(creditsText)
			
			// Clear only the exact space needed
			MoveCursor(x, y)
			fmt.Print(strings.Repeat(" ", totalLength))
			MoveCursor(x, y)
			fmt.Printf("%s%s %s%s%s", CyanHi, name, Yellow, creditsText, Reset)
		} else {
			// Right side players: name followed by credits, left-aligned at fixed position
			textX := x - 16  // Fixed 16 columns to the left of portrait
			
			// Calculate exact space needed: name + space + $ + digits
			creditsText := fmt.Sprintf("$%d", credits)
			totalLength := len(name) + 1 + len(creditsText)
			
			// Clear only the exact space needed
			MoveCursor(textX, y)
			fmt.Print(strings.Repeat(" ", totalLength))
			MoveCursor(textX, y)
			fmt.Printf("%s%s %s%s%s", CyanHi, name, Yellow, creditsText, Reset)
		}
	}
}

