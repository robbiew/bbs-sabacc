// ScreenLayout manages the persistent UI layout for the Sabacc game
type ScreenLayout struct {
	// Terminal dimensions
	TerminalW int
	TerminalH int

	// Fixed screen positions for 4 AI players + human player layout
	// AI Player positions (corners of screen)
	AIPlayer1X int // Top-left AI player (Phoo_ja)
	AIPlayer1Y int
	AIPlayer2X int // Top-right AI player (Rsh-Taac)
	AIPlayer2Y int
	AIPlayer3X int // Bottom-left AI player (Soladi)
	AIPlayer3Y int
	AIPlayer4X int // Bottom-right AI player (Ky'Ola)
	AIPlayer4Y int

	// Central game log area
	GameLogX int // Center area for scrolling messages - X pos
	GameLogY int // Center area for scrolling messages - Y pos
	GameLogW int // Width of game log area
	GameLogH int // Height of game log area

	// Human player area (bottom center)
	HumanPlayerX int // Player cards area
	HumanPlayerY int
	HumanNameY   int // Player name/info line

	// Turn indicator area
	TurnIndicatorX int
	TurnIndicatorY int

	// Pot info area  
	PotInfoX int
	PotInfoY int

	// Status bar area (Round/Deck display)
	StatusBarX int
	StatusBarY int

	// Bottom status and menu
	StatusY int // Bottom status line (pots, credits)
	MenuY   int // Action buttons line

	// Card display settings
	CardWidth   int // Width of each card display
	CardHeight  int // Height of each card display
	MaxCardsRow int // Maximum cards per row

	// Face art dimensions
	FaceWidth  int // Width of character face art
	FaceHeight int // Height of character face art

	// Portrait system
	PortraitManager *PortraitManager // Manages external ANSI portrait art

	// Game log system
	GameLog *GameLog

}

// GameLog manages the scrolling message area
type GameLog struct {
	Messages []string // Circular buffer of messages
	MaxLines int      // Maximum lines to display
	StartY   int      // Starting Y position for display
	Width    int      // Width of log area
}

// MenuOption represents a menu choice
type MenuOption struct {
	Key         rune
	Description string
	Enabled     bool
}


// NewScreenLayout creates a new screen layout for fixed 79x24 dimensions
func NewScreenLayout(termW, termH int) *ScreenLayout {
	// Force fixed dimensions regardless of actual terminal size
	fixedW := 79
	fixedH := 24

	layout := &ScreenLayout{
		TerminalW: fixedW,
		TerminalH: fixedH,

		// AI Player positions (4 corners) - adjusted for 9-column portraits
		AIPlayer1X: 1, // Top-left (PHOOJA)
		AIPlayer1Y: 2,
		AIPlayer2X: 71, // Top-right (ASH-TAAC) 
		AIPlayer2Y: 2,
		AIPlayer3X: 1, // Bottom-left (OOLANGA)
		AIPlayer3Y: 9,
		AIPlayer4X: 71, // Bottom-right (KY'ALA) - 9 chars + padding
		AIPlayer4Y: 9,

		// Central game log area (blue bordered box from reference)
		GameLogX: 28,
		GameLogY: 5,
		GameLogW: 25, // Fixed width to match reference file
		GameLogH: 7,  

		// Human player area (bottom center - fixed for 79x24)
		HumanPlayerX: fixedW/2 - 15,
		HumanPlayerY: 17, // Move higher to give space for cards above menu
		HumanNameY:   15,

		// Turn indicator (below game log)
		TurnIndicatorX: 4,
		TurnIndicatorY: 19,

		// Pot info area 
		PotInfoX: 2,
		PotInfoY: 18,

		// Status bar area (left side - Round/Deck display)
		StatusBarX: 2,
		StatusBarY: 21,

		// Status and Menu UI elements
		StatusY: 13, 
		MenuY:   24, // Menu on bottom row for compact display

		// Card and face display settings
		CardWidth:   6,                 // card width (matches card database)
		CardHeight:  5,                 // card height 
		MaxCardsRow: 8,                 // card row limit 
		FaceWidth:   portraitWidth + 2, // Portrait width + 2 for borders (9+2=11)
		FaceHeight:  portraitHeight,    // Portrait height (6 rows)
	}

	// Initialize game log with proper dimensions
	layout.GameLog = &GameLog{
		Messages: make([]string, 0),
		MaxLines: layout.GameLogH+2, 
		StartY:   layout.GameLogY + 2, // Inside border
		Width:    layout.GameLogW+4, // Inside border with padding
	}

	// Initialize portrait manager for external ANSI art
	layout.PortraitManager = NewPortraitManager()



	return layout
}

// InitializeScreen draws the static UI elements once
func (sl *ScreenLayout) InitializeScreen() {
	ClearScreen()

	PrintAnsiLoc(SabaccLogo, 29, 2)
	PrintAnsiLoc(LogBorder, sl.GameLogX-1, sl.GameLogY-1)

	// Draw the 4 AI player areas with face art
	sl.drawAIPlayerAreas()

	// Draw central game log with blue border
	sl.drawGameLogBorder()

	// Initialize game log
	sl.GameLog.Clear()
}

