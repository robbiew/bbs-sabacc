// RefreshGameLog redraws the game log area with blue background and wraps long text
func (sl *ScreenLayout) RefreshGameLog() {
	// Clear the log area with blue background
	for i := 0; i < sl.GameLogH; i++ {
		MoveCursor(sl.GameLogX, sl.GameLogY+i)
		fmt.Printf("\x1b[30;44m%s\x1b[0m", strings.Repeat(" ", sl.GameLogW))
	}

	// Get recent messages and wrap them
	messages := sl.GameLog.GetRecentMessages()
	wrappedLines := []string{}
	
	// Wrap each message to fit within the log width (23 characters for text)
	maxTextLen := 23
	for _, msg := range messages {
		cleanMsg := stripANSI(msg)
		if len(cleanMsg) <= maxTextLen {
			wrappedLines = append(wrappedLines, msg)
		} else {
			// Wrap the message into multiple lines
			wrapped := wrapText(msg, maxTextLen)
			wrappedLines = append(wrappedLines, wrapped...)
		}
	}
	
	// Display the most recent wrapped lines (from bottom up)
	linesToShow := sl.GameLogH
	startIndex := len(wrappedLines) - linesToShow
	if startIndex < 0 {
		startIndex = 0
	}
	
	for i := 0; i < linesToShow && startIndex+i < len(wrappedLines); i++ {
		line := wrappedLines[startIndex+i]
		MoveCursor(sl.GameLogX, sl.GameLogY+i)
		
		// Start with blue background for entire line
		fmt.Print("\x1b[30;44m")
		
		// Print message with padding
		fmt.Printf(" %s", line)
		
		// Calculate remaining space and fill with blue background
		msgLen := len(stripANSI(line))
		if msgLen < maxTextLen {
			remaining := maxTextLen - msgLen
			fmt.Printf("\x1b[30;44m%s", strings.Repeat(" ", remaining))
		}
		fmt.Print(" ") // Right padding
		
		fmt.Print("\x1b[0m") // Reset at end of line
	}
}

// RenderPlayerCards renders cards for a player
func (sl *ScreenLayout) RenderPlayerCards(playerIndex int, cards []Card, staticField []Card, faceDown bool, renderer *CardRenderer, round, deckSize, handPot, sabaccPot int) {
	var x, y int

	switch playerIndex {
	case 0: // Human player
		x, y = sl.HumanPlayerX, sl.HumanPlayerY
	case 1: // AI 1 - Top-left, cards next to portrait under name
		x, y = sl.AIPlayer1X+portraitWidth+1, sl.AIPlayer1Y+1
	case 2: // AI 2 - Top-right, cards left of portrait under name  
		x, y = sl.AIPlayer2X-16, sl.AIPlayer2Y+1
	case 3: // AI 3 - Bottom-left, cards next to portrait under name
		x, y = sl.AIPlayer3X+portraitWidth+1, sl.AIPlayer3Y+1
	case 4: // AI 4 - Bottom-right, cards left of portrait under name
		x, y = sl.AIPlayer4X-16, sl.AIPlayer4Y+1
	default:
		return
	}

	// Clear the card area first
	sl.ClearPlayerArea(playerIndex)
	
	// Redraw status bar and pot info after clearing human player area (since they get wiped out)
	if playerIndex == 0 {
		sl.UpdateStatusLine(round, 0, 0, deckSize) // Use 0 for pots since this is just for Round/Deck display
		sl.drawPotInfo(handPot, sabaccPot, 0) // Redraw pot info with actual values
	}

	// Render cards
	for i, card := range cards {
		// More robust check for static field cards
		isStatic := false
		for _, staticCard := range staticField {
			if card.Value == staticCard.Value && card.Suit == staticCard.Suit && card.Name == staticCard.Name {
				isStatic = true
				break
			}
		}


		if faceDown {
			// Show face-down AI cards as solid colored blocks to hide values from human player
			if playerIndex > 0 { // AI players
				suitColor := getSuitColorForAI(card)

				// Position each card with proper spacing (2 characters per card: block + space)
				cardX := x + (i * 2)
				MoveCursor(cardX, y)
				fmt.Printf("%s%s%s", suitColor, SOLID_BLOCK, Reset) // Use solid block to hide card value
				
				// Add yellow asterisk under static field cards for AI players
				if isStatic {
					MoveCursor(cardX, y+1)
					fmt.Printf("%s*%s", Yellow, Reset)
				}
			} else {
				// Human player face-down cards
				cardX := x + (i * 4) // Keep original spacing for human cards
				MoveCursor(cardX, y)
				fmt.Printf("%s%s%s%s", Yellow, SOLID_BLOCK, SOLID_BLOCK, Reset)
				
				// Add yellow asterisk under static field cards for human player
				if isStatic {
					MoveCursor(cardX+1, y+sl.CardHeight)
					fmt.Printf("%s*%s", Yellow, Reset)
				}
			}
		} else {
			// Show actual card for human player
			if renderer != nil && playerIndex == 0 {
				// Render card row by row with proper cursor positioning
				cardX := x + (i * 4) // Keep original spacing for human cards
				sl.renderCardAtPosition(cardX, y, card, renderer)
				if isStatic {
					MoveCursor(cardX+2, y+sl.CardHeight)
					fmt.Printf("%s*%s", Yellow, Reset)
				}
			} else {
				// Fallback text representation
				cardX := x + (i * 4)
				MoveCursor(cardX, y)
				fmt.Printf("[%s]", card.String())
				if isStatic {
					MoveCursor(cardX+1, y+1)
					fmt.Printf("%s*%s", Yellow, Reset)
				}
			}
		}
	}

	// Render AI static field card values with proper spacing and +/- indicators
	if playerIndex > 0 {
		for i, card := range staticField {
			cardX := x + (i * 2) // Match the 2-character spacing used for AI cards
			MoveCursor(cardX, y+2) // Position below the asterisk
			
			// Display value with +/- indicator
			if card.Value > 0 {
				fmt.Printf("%s+%d%s", Yellow, card.Value, Reset)
			} else if card.Value < 0 {
				fmt.Printf("%s%d%s", Yellow, card.Value, Reset) // Negative already has - sign
			} else {
				fmt.Printf("%s0%s", Yellow, Reset)
			}
		}
	}
}


// GameLog methods
func (gl *GameLog) AddMessage(message, msgType string) {
	// Add color coding based on message type
	coloredMsg := message
	switch msgType {
	case "error":
		coloredMsg = Red + message + Reset
	case "success":
		coloredMsg = Green + message + Reset
	case "warning":
		coloredMsg = Yellow + message + Reset
	case "important":
		coloredMsg = RedHi + message + Reset
	case "action":
		coloredMsg = Cyan + message + Reset
	case "info":
		coloredMsg = White + message + Reset
	}

	gl.Messages = append(gl.Messages, coloredMsg)

	// Keep only recent messages (circular buffer)
	if len(gl.Messages) > gl.MaxLines*3 {
		gl.Messages = gl.Messages[len(gl.Messages)-gl.MaxLines:]
	}
}

func (gl *GameLog) GetRecentMessages() []string {
	if len(gl.Messages) <= gl.MaxLines {
		return gl.Messages
	}
	return gl.Messages[len(gl.Messages)-gl.MaxLines:]
}

func (gl *GameLog) Clear() {
	gl.Messages = make([]string, 0)
}

// Helper functions for AI card rendering

// getSuitColorForAI returns the appropriate color for AI card blocks based on suit
func getSuitColorForAI(card Card) string {
	switch card.Suit {
	case "Sabers", "Flasks":
		return Green // Green foreground for Sabers and Flasks
	case "Coins", "Staves":
		return Yellow // Yellow foreground for Coins and Staves
	case "Arcana":
		return Red // Red foreground for Arcana cards
	default:
		return White // White foreground for unknown suits
	}
}


// renderCardAtPosition renders a card at a specific position using proper cursor positioning
func (sl *ScreenLayout) renderCardAtPosition(x, y int, card Card, renderer *CardRenderer) {
	// Get card data from the database
	cardID := card.String()
	data, _, height, err := renderer.Database.GetCardData(cardID)
	if err != nil {
		// Fallback to simple representation
		MoveCursor(x, y)
		fmt.Printf("[%s]", card.String())
		return
	}

	// Split ANSI data into lines and render each line
	lines := strings.Split(string(data), "\r\n")
	for i, line := range lines {
		if i >= height {
			break
		}
		MoveCursor(x, y+i)
		fmt.Print(line)
	}
}

// wrapText wraps a message to fit within the specified width, preserving ANSI color codes
func wrapText(text string, maxWidth int) []string {
	if len(stripANSI(text)) <= maxWidth {
		return []string{text}
	}
	
	var lines []string
	remaining := text
	currentColor := "" // Track the active color code
	
	for len(stripANSI(remaining)) > maxWidth {
		// Find the best break point within maxWidth characters
		breakPoint := maxWidth
		cleanText := stripANSI(remaining)
		
		// Look for a space to break on (word wrapping)
		for i := maxWidth - 1; i >= maxWidth/2; i-- {
			if i < len(cleanText) && cleanText[i] == ' ' {
				breakPoint = i
				break
			}
		}
		
		// Extract the line up to the break point, preserving ANSI codes
		line := extractTextWithANSI(remaining, breakPoint)
		
		// Extract the current color from this line
		currentColor = extractCurrentColor(line)
		
		lines = append(lines, line)
		
		// Remove the extracted portion from remaining text
		remaining = remaining[findANSIAwarePosition(remaining, breakPoint):]
		
		// Skip leading spaces in the next line
		for len(remaining) > 0 && remaining[0] == ' ' {
			remaining = remaining[1:]
		}
		
		// Prepend the current color to the continuation line if we have one
		if currentColor != "" && len(stripANSI(remaining)) > 0 {
			remaining = currentColor + remaining
		}
	}
	
	// Add any remaining text as the last line
	if len(stripANSI(remaining)) > 0 {
		// Ensure final line has proper color if needed
		if currentColor != "" && !strings.Contains(remaining, "\x1b[") {
			remaining = currentColor + remaining
		}
		lines = append(lines, remaining)
	}
	
	return lines
}

// extractTextWithANSI extracts text up to a certain character count while preserving ANSI codes
func extractTextWithANSI(text string, charCount int) string {
	if charCount <= 0 {
		return ""
	}
	
	var result strings.Builder
	visibleCount := 0
	i := 0
	
	for i < len(text) && visibleCount < charCount {
		if text[i] == '\x1b' && i+1 < len(text) && text[i+1] == '[' {
			// ANSI escape sequence - copy it entirely
			start := i
			i += 2
			for i < len(text) && text[i] != 'm' {
				i++
			}
			if i < len(text) {
				i++ // Include the 'm'
			}
			result.WriteString(text[start:i])
		} else {
			// Regular character
			result.WriteByte(text[i])
			visibleCount++
			i++
		}
	}
	
	return result.String()
}

// extractCurrentColor extracts the last color code from a text string
func extractCurrentColor(text string) string {
	lastColorStart := -1
	i := 0
	
	for i < len(text)-1 {
		if text[i] == '\x1b' && text[i+1] == '[' {
			lastColorStart = i
		}
		i++
	}
	
	if lastColorStart == -1 {
		return ""
	}
	
	// Extract from lastColorStart to the 'm' character
	for i := lastColorStart + 2; i < len(text); i++ {
		if text[i] == 'm' {
			return text[lastColorStart : i+1]
		}
	}
	
	return ""
}

// findANSIAwarePosition finds the byte position after skipping a certain number of visible characters
func findANSIAwarePosition(text string, charCount int) int {
	if charCount <= 0 {
		return 0
	}
	
	visibleCount := 0
	i := 0
	
	for i < len(text) && visibleCount < charCount {
		if text[i] == '\x1b' && i+1 < len(text) && text[i+1] == '[' {
			// Skip ANSI escape sequence
			i += 2
			for i < len(text) && text[i] != 'm' {
				i++
			}
			if i < len(text) {
				i++ // Skip the 'm'
			}
		} else {
			// Regular character
			visibleCount++
			i++
		}
	}
	
	return i
}
