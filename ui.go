// RefreshGameLog redraws the game log area with blue background
func (sl *ScreenLayout) RefreshGameLog() {
	// Clear the log area with blue background
	for i := 0; i <= sl.GameLogH; i++ {
		MoveCursor(sl.GameLogX, sl.GameLogY+i)
		fmt.Printf("\x1b[30;44m%s\x1b[0m", strings.Repeat(" ", sl.GameLogW))
	}

	// Display recent messages with blue background
	messages := sl.GameLog.GetRecentMessages()
	for i, msg := range messages {
		if i < sl.GameLogH {
			MoveCursor(sl.GameLogX, sl.GameLogY+i)
			
			// Start with blue background for entire line
			fmt.Print("\x1b[30;44m")
			
			// Truncate message if too long
			if len(msg) > sl.GameLogW-1 {
				msg = msg[:sl.GameLogW-3] + "..."
			}
			
			// Print message with padding
			fmt.Printf(" %s", msg)
			
			// Calculate remaining space and fill with blue background
			msgLen := len(stripANSI(msg))
			if msgLen < sl.GameLogW-2 {
				remaining := sl.GameLogW - msgLen - 2
				fmt.Printf("\x1b[30;44m%s", strings.Repeat(" ", remaining))
			}
			
			fmt.Print("\x1b[0m") // Reset at end of line
		}
	}
}

// RenderPlayerCards renders cards for a player
func (sl *ScreenLayout) RenderPlayerCards(playerIndex int, cards []Card, staticField []Card, faceDown bool, renderer *CardRenderer) {
	var x, y int

	switch playerIndex {
	case 0: // Human player
		x, y = sl.HumanPlayerX, sl.HumanPlayerY
	case 1: // AI 1 - Top-left, cards at bottom of corner area
		x, y = sl.AIPlayer1X, 8
	case 2: // AI 2 - Top-right, cards at bottom of corner area
		x, y = sl.AIPlayer2X, 8
	case 3: // AI 3 - Bottom-left, cards at bottom of corner area
		x, y = sl.AIPlayer3X, sl.AIPlayer3Y+sl.FaceHeight+1
	case 4: // AI 4 - Bottom-right, cards at bottom of corner area
		x, y = sl.AIPlayer4X, sl.AIPlayer4Y+sl.FaceHeight+1
	default:
		return
	}

	// Clear the card area first
	sl.ClearPlayerArea(playerIndex)

	// Render cards
	for i, card := range cards {
		isStatic := false
		for _, staticCard := range staticField {
			if card == staticCard {
				isStatic = true
				break
			}
		}

		if faceDown {
			// Show face-down AI cards as colored suit blocks (like reference image)
			if playerIndex > 0 { // AI players
				suitColor := getSuitColorForAI(card)
				valueStr := getCardValueDisplay(card)

				// Position each card with proper spacing (one space between cards)
				cardX := x + (i * (len(valueStr) + 1))
				MoveCursor(cardX, y)
				fmt.Printf("%s%s%s", suitColor, valueStr, Reset)
			} else {
				// Human player face-down cards
				cardX := x + (i * 4) // Keep original spacing for human cards
				MoveCursor(cardX, y)
				fmt.Printf("%s%s%s%s", Yellow, SOLID_BLOCK, SOLID_BLOCK, Reset)
			}
		} else {
			// Show actual card for human player
			if renderer != nil && playerIndex == 0 {
				// Render card row by row with proper cursor positioning
				cardX := x + (i * 4) // Keep original spacing for human cards
				sl.renderCardAtPosition(cardX, y, card, renderer)
				if isStatic {
					MoveCursor(cardX+2, y+sl.CardHeight)
					fmt.Print("*")
				}
			} else {
				// Fallback text representation
				cardX := x + (i * 4)
				MoveCursor(cardX, y)
				fmt.Printf("[%s]", card.String())
				if isStatic {
					MoveCursor(cardX+1, y+1)
					fmt.Print("*")
				}
			}
		}
	}

	// Render AI static field card values
	if playerIndex > 0 {
		for i, card := range staticField {
			cardX := x + (i * 4)
			MoveCursor(cardX, y+1)
			fmt.Printf("%s%d%s", Yellow, card.Value, Reset)
		}
	}
}

// RenderStaticField renders the static field cards
func (sl *ScreenLayout) RenderStaticField(cards []Card, renderer *CardRenderer) {
	// Position static field below human player cards
	staticY := sl.HumanPlayerY + sl.CardHeight + 2

	// Clear static field area
	MoveCursor(sl.HumanPlayerX, staticY-1)
	fmt.Print(EraseLine)
	fmt.Printf("%sStatic Field:%s", Cyan, Reset)

	for i := 0; i < 2; i++ { // Clear 2 lines for static field
		MoveCursor(sl.HumanPlayerX, staticY+i)
		fmt.Print(EraseLine)
	}

	// Render static field cards
	for i, card := range cards {
		cardX := sl.HumanPlayerX + (i * (sl.CardWidth + 1))
		if renderer != nil {
			MoveCursor(cardX, staticY)
			renderer.RenderCard(card)
		} else {
			// Fallback text representation
			MoveCursor(cardX, staticY)
			fmt.Printf("[%s]", card.String())
		}
	}
}

// GameLog methods
func (gl *GameLog) AddMessage(message, msgType string) {
	// Add color coding based on message type
	coloredMsg := message
	switch msgType {
	case "error":
		coloredMsg = Red + message + Reset
	case "success":
		coloredMsg = Green + message + Reset
	case "warning":
		coloredMsg = Yellow + message + Reset
	case "important":
		coloredMsg = RedHi + message + Reset
	case "action":
		coloredMsg = Cyan + message + Reset
	case "info":
		coloredMsg = White + message + Reset
	}

	gl.Messages = append(gl.Messages, coloredMsg)

	// Keep only recent messages (circular buffer)
	if len(gl.Messages) > gl.MaxLines*3 {
		gl.Messages = gl.Messages[len(gl.Messages)-gl.MaxLines:]
	}
}

func (gl *GameLog) GetRecentMessages() []string {
	if len(gl.Messages) <= gl.MaxLines {
		return gl.Messages
	}
	return gl.Messages[len(gl.Messages)-gl.MaxLines:]
}

func (gl *GameLog) Clear() {
	gl.Messages = make([]string, 0)
}

// Helper functions for AI card rendering

// getSuitColorForAI returns the appropriate color for AI card blocks based on suit
func getSuitColorForAI(card Card) string {
	switch card.Suit {
	case "Sabers", "Flasks":
		return "\x1b[32;42m" // Green background for Sabers and Flasks
	case "Coins", "Staves":
		return "\x1b[33;43m" // Brown/Yellow background for Coins and Staves
	case "Arcana":
		return "\x1b[31;41m" // Red background for Arcana cards
	default:
		return "\x1b[37;47m" // White background for unknown suits
	}
}

// getCardValueDisplay returns a short display value for AI cards
func getCardValueDisplay(card Card) string {
	if card.Value > 0 {
		return fmt.Sprintf("%d", card.Value)
	} else if card.Value < 0 {
		return fmt.Sprintf("%d", card.Value) // Show negative values
	}
	return "0"
}

// renderCardAtPosition renders a card at a specific position using proper cursor positioning
func (sl *ScreenLayout) renderCardAtPosition(x, y int, card Card, renderer *CardRenderer) {
	// Get card data from the database
	cardID := card.String()
	data, _, height, err := renderer.Database.GetCardData(cardID)
	if err != nil {
		// Fallback to simple representation
		MoveCursor(x, y)
		fmt.Printf("[%s]", card.String())
		return
	}

	// Split ANSI data into lines and render each line
	lines := strings.Split(string(data), "\r\n")
	for i, line := range lines {
		if i >= height {
			break
		}
		MoveCursor(x, y+i)
		fmt.Print(line)
	}
}


